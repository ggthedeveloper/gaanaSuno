// Helper to generate dynamic SVG artwork data URLs
export function generateCoverArt(title: string, subtitle: string, bgColors: [string, string], accentColor: string): string {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 400 400" width="400" height="400">
    <defs>
      <linearGradient id="g" x1="0%" y1="0%" x2="100%" y2="100%">
        <stop offset="0%" stop-color="${bgColors[0]}"/>
        <stop offset="100%" stop-color="${bgColors[1]}"/>
      </linearGradient>
      <radialGradient id="glow" cx="50%" cy="30%" r="60%">
        <stop offset="0%" stop-color="${accentColor}" stop-opacity="0.4"/>
        <stop offset="100%" stop-color="${bgColors[1]}" stop-opacity="0"/>
      </radialGradient>
      <linearGradient id="disc" x1="0%" y1="0%" x2="100%" y2="0%">
        <stop offset="0%" stop-color="#111"/>
        <stop offset="50%" stop-color="#2a2a2a"/>
        <stop offset="100%" stop-color="#111"/>
      </linearGradient>
    </defs>
    <rect width="400" height="400" fill="url(#g)" rx="24"/>
    <rect width="400" height="400" fill="url(#glow)" rx="24"/>
    
    <!-- Stylized Vinyl / Raga Motif -->
    <g transform="translate(200, 160)">
      <circle r="100" fill="url(#disc)" stroke="#333" stroke-width="2"/>
      <circle r="75" fill="none" stroke="#222" stroke-width="1.5"/>
      <circle r="50" fill="none" stroke="#333" stroke-width="1.5"/>
      <circle r="35" fill="${accentColor}" fill-opacity="0.9"/>
      <circle r="8" fill="#111"/>
    </g>
    
    <text x="200" y="310" font-family="system-ui, -apple-system, sans-serif" font-weight="900" font-size="24" fill="#ffffff" text-anchor="middle" letter-spacing="-0.5">${title}</text>
    <text x="200" y="340" font-family="system-ui, -apple-system, sans-serif" font-weight="500" font-size="14" fill="${accentColor}" text-anchor="middle" letter-spacing="0.5">${subtitle}</text>
  </svg>`;
  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
}

